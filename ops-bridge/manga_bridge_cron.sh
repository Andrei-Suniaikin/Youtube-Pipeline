#!/bin/bash
# Мост манхвы: подкладывать готовые ролики в очередь заливки понемногу.
#
# По три за раз и раз в два часа — чтобы очередь профиля 21 не разбухала: он несёт
# и ВВ2, и всю манхву, а одна заливка идёт 12-15 минут. Сколько роликов держать на
# канале, решает сам мост (не больше пяти запланированных вперёд).
LOG=/root/ops_bridge/manga_bridge.log
{
  echo "── $(date '+%d.%m %H:%M') ──"
  python3 /root/ops_bridge/manga_bridge.py --apply --limit 3
} >> "$LOG" 2>&1
tail -c 200000 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
