# Текущий язык (по умолчанию русский)
_current_language = 'ru'

_language_loaded = False

def get_language():
    """Получает текущий язык из кэша; файл читается только один раз при старте."""
    global _current_language, _language_loaded
    if _language_loaded:
        return _current_language
    try:
        if os.path.exists(LANG_CONFIG_PATH):
            with open(LANG_CONFIG_PATH, 'r', encoding='utf-8', errors='replace') as f:
                config = json.load(f)
                _current_language = config.get('language', 'ru')
        else:
            _current_language = 'ru'
    except Exception:
        _current_language = 'ru'
    _language_loaded = True
    return _current_language

def set_language(lang):
    """Устанавливает язык и сохраняет в конфиг"""
    global _current_language, _language_loaded
    if lang not in TRANSLATIONS:
        lang = 'ru'
    _current_language = lang
    _language_loaded = True
    try:
        config = {'language': lang}
        with open(LANG_CONFIG_PATH, 'w', encoding='utf-8', errors='replace') as f:
            json.dump(config, f, indent=2, ensure_ascii=False)
    except Exception:
        pass

def _(key, *args, **kwargs):
    """
    Функция перевода. Использование:
    _('key') - простой перевод
    _('key', count=5) - с форматированием (если нужно)
    """
    lang = get_language()
    translation = TRANSLATIONS.get(lang, TRANSLATIONS['ru']).get(key, key)
    
    # Если translation None или не строка, возвращаем key
    if not translation or not isinstance(translation, str):
        translation = key
    
    # Если есть аргументы для форматирования
    if args or kwargs:
        try:
            return translation.format(*args, **kwargs)
        except (KeyError, IndexError, AttributeError):
            return translation
    
    return translation

def get_available_languages():
    """Возвращает список доступных языков"""
    return list(TRANSLATIONS.keys())

