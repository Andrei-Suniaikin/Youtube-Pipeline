#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Идентификатор донорского ролика — одно место на всю платформу.

Отдельный модуль без зависимостей нарочно: этим разбором пользуются и схема (разовое
заполнение колонки при миграции), и постановка ссылок в план, и клиент субтитров. Класть
его в `pub_remote` значило бы тянуть `requests` в миграцию схемы, а держать вторую копию
регулярки — рано или поздно развести две «правды» о том, что такое один и тот же ролик.
"""

from __future__ import annotations

import re

YT_ID_RE = re.compile(r"(?:v=|youtu\.be/|/shorts/|/embed/)([A-Za-z0-9_-]{11})")


def video_id(url: str) -> str:
    """Одиннадцать символов идентификатора — или пусто, если это не ссылка YouTube.

    Одно и то же видео приходит в разных написаниях: `youtu.be/X`, `watch?v=X`,
    `watch?v=X&t=30`, ссылка с `si=…` из кнопки «Поделиться», `/shorts/X`. Для человека
    это один ролик, и для проверки «этот донор уже взят» — тоже.
    """
    m = YT_ID_RE.search(url or "")
    if m:
        return m.group(1)
    tail = (url or "").rstrip("/").rsplit("/", 1)[-1]
    return tail if re.fullmatch(r"[A-Za-z0-9_-]{11}", tail) else ""
