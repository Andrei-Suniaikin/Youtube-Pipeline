#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Опознание принятого ролика: тот ли это файл, который допустили в очередь.

Между допуском и отправкой проходит время. Задание лежит в очереди, пока за ним не
придёт машина с нужным профилем AdsPower, а профиль бывает занят часами (своя заливка,
чужой конвейер на той же машине, человек руками). Всё это время в задании записан
только ПУТЬ к файлу — и нода получала то, что лежит по этому пути в момент выдачи.

Путь у рендера постоянный: приём результата кладёт mp4 в `render/<номер>.mp4` через
`os.replace`, а перезапуск того же рендера пишет туда же (`queue_tasks.render_sha256`
при перезахвате обнуляется — см. `server/main.py`, ручка claim). Значит пересборка
подменяет файл, не меняя в задании ни строчки: на канал уходит версия, которую никто
не принимал. Отменить это нельзя — ролик уже в YouTube.

Опознание состоит из двух независимых частей, и нужны обе:

* **версия сборки** — какой рендер дал файл и чем он закончился. Ловит «проект
  пересобрали»: у выпуска другой номер рендера либо у прежнего другая квитанция.
  Файл при этом может лежать на месте целым — он просто больше не та версия;
* **отпечаток файла** — размер и края содержимого. Ловит подмену мимо кабинета:
  перезапуск рендера по тому же номеру, ручная замена, недокачанный остаток.

Почему не полный SHA файла на каждом шаге: ролик весит гигабайты, сверка нужна дважды
за выпуск, и считать её пришлось бы на том же сервере, который в это время рендерит.
Чтение двух мегабайт стоит миллисекунды и не зависит от длины ролика. Полный хэш у нас
и так есть — его один раз считает приём результата рендера, и он лежит в квитанции;
именно он и есть «версия сборки», а края читаются, чтобы заметить подмену файла,
о которой квитанция знать не может.

Почему края, а не только размер: пересобранный mp4 почти всегда другой длины, но
«почти» тут мало. В начале и в конце файла лежит moov — индекс кадров; он меняется от
любой пересборки, даже если длина случайно совпала.

Чего отпечаток по краям не увидит: правку в середине многогигабайтного файла, не
изменившую ни длины, ни краёв. Такое не бывает от пересборки — пересборка переписывает
файл целиком, и её ловит версия сборки, — а стоило бы это чтения всего ролика на каждой
выдаче задания. Это осознанный размен, а не недосмотр.

Почему время записи файла хранится, но в сверке НЕ участвует: восстановление из бэкапа
и обычный `cp` переставляют mtime, не трогая байты. Отказать исправному ролику из-за
этого — ложная тревога, а она здесь дорогая: готовый выпуск встанет и будет ждать
человека. Время храним, чтобы человеку было что прочитать в объяснении отказа.

Пустое значение здесь всегда означает «не знаем» и никогда — «ноль»: у выпуска может
не быть рендера в нашей очереди (ролик пришёл другим путём), и это не повод считать
его версию совпавшей или несовпавшей.
"""

from __future__ import annotations

import hashlib
import json
import os

# Сколько байт с начала и с конца файла берём в отпечаток.
EDGE_BYTES = 1 << 20


def human_size(size) -> str:
    """Размер для человека. Не знаем — так и говорим, а не показываем ноль."""
    if size is None:
        return "неизвестно"
    size = int(size)
    if size >= 1024 ** 3:
        return f"{size / 1024 ** 3:.1f} ГБ".replace(".", ",")
    if size >= 1024 ** 2:
        return f"{size // 1024 ** 2} МБ"
    return f"{size} Б"


def file_mark(path: str) -> dict:
    """Отпечаток файла: размер, края содержимого, время записи. Нет файла — пусто.

    Края читаются двумя кусками по мегабайту; у файла короче двух мегабайт второй
    кусок перекрывается с первым, и это нормально — от файла хэш всё равно один.
    """
    if not path:
        return {}
    try:
        size = os.path.getsize(path)
        digest = hashlib.sha256(str(size).encode("ascii"))
        with open(path, "rb") as f:
            digest.update(f.read(EDGE_BYTES))
            if size > EDGE_BYTES:
                f.seek(size - EDGE_BYTES)
                digest.update(f.read(EDGE_BYTES))
        mtime = os.stat(path).st_mtime_ns
    except OSError:
        return {}
    return {"size": size, "edges": digest.hexdigest(), "mtime": mtime}


def build_mark(c, release_id: str) -> dict:
    """Версия сборки выпуска: номер рендера и его квитанция.

    Номер берём у выпуска, а не у задания заливки: если проект пересобрали новым
    рендером, у выпуска меняется именно он, а задание про это ничего не знает.
    """
    row = c.execute(
        "SELECT remote_job_id FROM pub_release_jobs WHERE release_id=? "
        "AND service='vsgen' AND kind='render'", (release_id,)).fetchone()
    job = (row["remote_job_id"] if row and row["remote_job_id"] else "")
    mark = {"job": str(job or ""), "status": "", "out": "", "sha256": "", "size": None}
    if not mark["job"]:
        return mark
    task = c.execute(
        "SELECT status, output_rel, render_sha256, render_size FROM queue_tasks "
        "WHERE job_id=? AND kind='render'", (mark["job"],)).fetchone()
    if task is None:
        return mark
    mark["status"] = task["status"] or ""
    mark["out"] = task["output_rel"] or ""
    mark["sha256"] = task["render_sha256"] or ""
    mark["size"] = task["render_size"]
    return mark


def passport(c, release_id: str, path: str) -> dict:
    """Опознание артефакта целиком: версия сборки плюс отпечаток файла."""
    return {"build": build_mark(c, release_id), "file": file_mark(path)}


def dump(mark: dict) -> str:
    """Опознание в строку для базы. Ключи по порядку: строки двух допусков сравнимы."""
    return json.dumps(mark, ensure_ascii=False, sort_keys=True)


def load(raw) -> dict:
    """Опознание из базы. Мусор и пустота читаются одинаково — как «не знаем»."""
    try:
        got = json.loads(raw or "")
    except (TypeError, ValueError):
        return {}
    return got if isinstance(got, dict) else {}


def mismatch(saved: dict, fresh: dict) -> str:
    """Чем нынешний артефакт отличается от принятого. Совпал — пустая строка.

    Порядок ответов важен: человеку нужна ПЕРВАЯ причина, по которой файл перестал
    быть тем самым, а не список всех следствий одной пересборки.

    Опознания нет вовсе (задание допущено до этой проверки) — молчим: объявить старое
    задание пересобранным значило бы остановить выпуски, с которыми всё в порядке.
    """
    if not saved:
        return ""
    old_file, new_file = saved.get("file") or {}, fresh.get("file") or {}
    if old_file and not new_file:
        return "файла ролика больше нет на месте — принятой версии не существует"
    if old_file and new_file:
        if old_file.get("size") != new_file.get("size"):
            return ("файл пересобран после приёмки: при приёмке было "
                    f"{human_size(old_file.get('size'))}, сейчас "
                    f"{human_size(new_file.get('size'))}")
        if old_file.get("edges") != new_file.get("edges"):
            return ("файл пересобран после приёмки: размер прежний, а содержимое "
                    "другое")
    old_build, new_build = saved.get("build") or {}, fresh.get("build") or {}
    if old_build.get("job") != new_build.get("job"):
        return ("проект пересобран после приёмки: ролик принимали от рендера "
                f"№{old_build.get('job') or 'неизвестно'}, а сейчас у выпуска рендер "
                f"№{new_build.get('job') or 'неизвестно'}")
    if old_build.get("job"):
        if new_build.get("status") != "done":
            return (f"рендер №{old_build['job']} запущен заново — принятой версии "
                    "ролика сейчас нет")
        if old_build.get("sha256") != new_build.get("sha256") \
                or old_build.get("size") != new_build.get("size") \
                or old_build.get("out") != new_build.get("out"):
            return (f"проект пересобран после приёмки: рендер №{old_build['job']} "
                    "переделан, квитанция другая")
    return ""


def refusal(why: str) -> str:
    """Отказ человеку: что случилось, что с деньгами, что делать дальше."""
    return (f"{why}. В YouTube ничего не отправлено и деньги не потрачены; "
            "заливка остановлена — нужна новая приёмка ролика")
