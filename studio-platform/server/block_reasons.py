def _out(kind: str, title: str, what: str, fix: str, revive: bool, who: str = "") -> dict:
    return {"kind": kind, "tag": TAGS[kind], "title": title, "what": what, "fix": fix,
            "who": who or WHO[kind], "revive": revive,
            "short": f"{TAGS[kind].lower()}: {title}"}


def _donor(title: str) -> dict:
    b = _out(DONOR, title, _DONOR_WHAT, _DONOR_FIX, False)
    b["short"] += " — нужен другой ролик"
    return b


_RECOVERY_SAID = re.compile(r"account recovery (?:blocked|needs the owner): (.+?)(?:\s+—\s+загрузка|$)")


def explain(reason) -> dict:
    """Причина остановки → {kind, tag, title, what, fix, who, revive, short}. {} — не узнали."""
    text = str(reason or "").strip()
    if not text:
        return {}
    if text.startswith(COVER_PRESET_MISSING):
        b = _out(CHANNEL, COVER_PRESET_TITLE,
                 "Ролик собран, выпуск стоит на обложке: рисовать её не по чему. "
                 "Без пресета студия обложку не заказывает — она нарисовалась бы "
                 "на чужих умолчаниях, платно и не та.",
                 "Выберите пресет обложки в настройках канала (или в пресете "
                 "производства канала). Выпуски, которые стоят из-за этого, "
                 "вернутся в работу сами в течение минуты.", True)
        b["short"] += " — выбрать в настройках канала"
        return b
    if text.startswith("у ролика нет субтитров, и распознать речь"):
        # 03.10.2026: студия сама пробовала распознать речь донора на Минске — не вышло.
        # Владелец: «не вышло — пускай падает, чтобы ребята по новой искали донора».
        b = _donor("не распознали речь донора")
        why = text.split("не вышло:", 1)[1].strip() if "не вышло:" in text else ""
        b["what"] = ("Субтитры у ролика отключены. Студия сама скачала звук донора и "
                     "распознавала речь на минской машине, но текста не получилось"
                     + (f" ({why})" if why else "") + ". Повтор этого не исправит.")
        return b
    m = _NO_SUBS_RE.match(text)
    if _GONE_RE.match(text) or (m and m.group(1) in ("VideoUnavailable", "VideoUnplayable")):
        b = _donor(GONE_SHORT)
        # «gone» — экран рисует красным: ролика больше нет, ждать нечего (13.10.2026).
        b.update(what=_GONE_WHAT, fix=_GONE_FIX, gone=True)
        return b
    if m:
        return _donor(_NO_SUBS.get(m.group(1) or "", "у донора нет субтитров"))
    if text.startswith("субтитры донора слишком короткие или пустые"):
        return _donor("у донора обрывок субтитров — на текст не хватит")
    if text.startswith("не разобрал ссылку на ролик"):
        return _donor("ссылка не на ролик YouTube")
    if text.startswith("модель отказалась писать название"):
        # 04.10.2026: отказ модели однажды ушёл на YouTube названием ролика. Теперь он
        # останавливает выпуск. Причина — тема донора (насилие и т.п.), повтор даст тот же
        # отказ, поэтому «вернуть в работу» здесь не поможет.
        b = _donor("модель отказалась писать название по теме")
        b["what"] = ("Ролик готов, но модель не стала писать название: тема донора попала "
                     "под её запреты. Её ответ-отказ мог бы уйти на YouTube вместо названия, "
                     "поэтому выпуск остановлен до заливки. Повтор даст тот же отказ.")
        return b
    if text.startswith(("UPLOAD_IN_PROGRESS", "нода молчит", "HTTPConnectionPool")):
        for start, title, what, fix in _CHECK:
            if text.startswith(start):
                return _out(CHECK, title, what, fix, False)
    for start, title, what, fix, who in _ACCESS:
        if start in text:
            if "RecoveryBlocked" in text:
                what += _RECOVERY_BLOCKED
            # 15.10.2026: заливщик теперь пишет, что именно ответил вход (какой шаг
            # Google спросил, почему отказ). Показываем это дословно — без него у 12
            # каналов причина остановки была неизвестна.
            said = _RECOVERY_SAID.search(text)
            if said and said.group(1).strip() not in ("RecoveryBlocked",):
                what += f" Дословно от заливщика: {' '.join(said.group(1).split())[:220]}."
            busy = _BUSY_BY.search(text)
            if busy:
                what = what.replace("другой учёткой команды", f"учёткой {busy.group(1)}")
                title = f"профиль AdsPower открыт у {busy.group(1)}"
                who = f"{busy.group(1)} — закрыть профиль в AdsPower"
            return _out(ACCESS, title, what, fix, True, who)
    for start, title, what, fix in _CHECK:
        if text.startswith(start):
            return _out(CHECK, title, what, fix, False)
    for start, title, what, fix in _COVER:
        if text.startswith(start):
            return _out(COVER, title, what, fix, False)
    for pattern, title, what in _STUDIO:
        if pattern.search(text):
            return _out(STUDIO, title, what, _STUDIO_FIX, True)
    return {}


