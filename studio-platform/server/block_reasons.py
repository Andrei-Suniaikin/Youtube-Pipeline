#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Почему выпуск остановлен — словами человека: чья это беда и что с ней делать.

03.10.2026, просьба владельца: «нужно чётко показывать, что не выбран пресет обложек» и
«нужно чётко показывать, что проблема в доноре, чтобы человек понимал». До этого экран
печатал причину как есть, красной строкой — «у ролика нет субтитров (VideoUnplayable)»,
— и рядом ставил «Вернуть в работу». Человек видел имя исключения вместо смысла, не
понимал, что дело не в студии, и жал кнопку, которая дала бы тот же отказ.

Здесь причина остановки, записанная движком (`pub_releases.blocked_reason`), переводится
в ответ на три вопроса — чья беда (`kind` + `tag`), что случилось (`title`, `what`) и что
делать (`fix`) — плюс признак, имеет ли смысл «Вернуть в работу» (`revive`). Одно место
на все экраны и на утреннюю сводку: перевод, живущий в двух местах, расходится первым же
исправлением формулировки.

Сами причины НЕ меняются: движок пишет их как писал, этот модуль только читает. Причину,
которую он не узнал, отдаёт пустым ответом — экран тогда показывает её как раньше. Узнаём
по началу строки, которую ставит движок (`pub_remote.donor_subs`,
`pub_services.do_cover_ready`): это наши собственные тексты, а не ответ чужой системы.
"""
from __future__ import annotations

import re

DONOR = "donor"
CHANNEL = "channel"

TAGS = {DONOR: "Проблема в доноре", CHANNEL: "Настройка канала"}

# Ровно эта строка пишется движком в blocked_reason (pub_services.do_cover_ready).
COVER_PRESET_MISSING = "у канала не выбран пресет обложек"

# Что значит имя исключения библиотеки субтитров — для человека. Список закрытый, тот
# же, что `pub_remote._no_subtitles`: всё прочее движок приговором ролику не считает.
# VideoUnplayable/VideoUnavailable доходят сюда только после проверки, что ролика правда
# нет на YouTube (`pub_remote._video_really_gone`), — отсюда «удалён или закрыт».
_NO_SUBS = {
    "TranscriptsDisabled": "автор ролика отключил субтитры",
    "NoTranscriptFound": "у ролика нет субтитров ни на одном языке",
    "NoTranscriptAvailable": "у ролика нет субтитров ни на одном языке",
    # Формулировка владельца 03.10.2026: «пишем прямо — автор скрыл видео, достать
    # субтитры невозможно».
    "VideoUnavailable": "автор скрыл видео — достать субтитры невозможно",
    "VideoUnplayable": "автор скрыл видео — достать субтитры невозможно",
    "AgeRestricted": "у ролика ограничение по возрасту — YouTube не отдаёт его субтитры",
}
_NO_SUBS_RE = re.compile(r"^у ролика нет субтитров(?:\s*\((\w+)\))?")

_DONOR_WHAT = ("Текст выпуска берётся из субтитров ролика-донора, а взять их неоткуда. "
               "Это свойство самого ролика на YouTube, а не сбой студии: повтор даст "
               "тот же ответ, денег на этот выпуск не потрачено.")
_DONOR_FIX = ("Уберите эту ссылку из плана и поставьте на канал другой ролик-донор — "
              "он займёт свободный выход.")


def _donor(title: str) -> dict:
    return {"kind": DONOR, "tag": TAGS[DONOR], "title": title,
            "what": _DONOR_WHAT, "fix": _DONOR_FIX, "revive": False,
            "short": f"{TAGS[DONOR].lower()}: {title} — нужен другой ролик"}


def explain(reason) -> dict:
    """Причина остановки → {kind, tag, title, what, fix, revive, short}. {} — не узнали."""
    text = str(reason or "").strip()
    if not text:
        return {}
    if text.startswith(COVER_PRESET_MISSING):
        title = "у канала не выбран пресет обложек"
        return {"kind": CHANNEL, "tag": TAGS[CHANNEL], "title": title,
                "what": ("Ролик собран, выпуск стоит на обложке: рисовать её не по чему. "
                         "Без пресета студия обложку не заказывает — она нарисовалась бы "
                         "на чужих умолчаниях, платно и не та."),
                "fix": ("Выберите пресет обложки в настройках канала (или в пресете "
                        "производства канала). Выпуски, которые стоят из-за этого, "
                        "вернутся в работу сами в течение минуты."),
                "revive": True,
                "short": f"{TAGS[CHANNEL].lower()}: {title} — выбрать в настройках канала"}
    if text.startswith("у ролика нет субтитров, и распознать речь"):
        # 03.10.2026: студия сама пробовала распознать речь донора на Минске — не вышло.
        # Владелец: «не вышло — пускай падает, чтобы ребята по новой искали донора».
        b = _donor("субтитров нет, и распознать речь донора не вышло")
        why = text.split("не вышло:", 1)[1].strip() if "не вышло:" in text else ""
        b["what"] = ("Субтитры у ролика отключены. Студия сама скачала звук донора и "
                     "распознавала речь на минской машине, но текста не получилось"
                     + (f" ({why})" if why else "") + ". Повтор этого не исправит.")
        return b
    m = _NO_SUBS_RE.match(text)
    if m:
        return _donor(_NO_SUBS.get(m.group(1) or "", "у ролика нет субтитров"))
    if text.startswith("субтитры донора слишком короткие или пустые"):
        return _donor("у ролика только обрывок субтитров — текста на выпуск не хватит")
    if text.startswith("не разобрал ссылку на ролик"):
        return _donor("ссылка не ведёт на ролик YouTube")
    return {}


# ───── недосмотры настройки канала, которые выпуск НЕ останавливают (03.10.2026) ─────
#
# Владелец о выпуске «Элемент №82. СВИНЕЦ»: «канал тут не настроен, но нигде не
# показывается, что проблема на стороне человека, который сидит за каналами». Выпуск шёл:
# пресета текста у канала нет, и рерайт пишет на своих умолчаниях — без ведущего, без
# названия канала. По решению владельца от 01.10 (п. 5) это предупреждение, а не отказ,
# — и сказано оно было одной строкой в журнале выпуска, куда никто не смотрит.
#
# Здесь — что показать рядом с выпуском, пока это ещё на него влияет: пресет текста —
# пока текст не написан; пресет обложек — пока выпуск до обложки не дошёл.

_PHASE_ORDER = ("created", "source_ready", "project_ready", "media_ready", "cover_ready")


def channel_gaps(rew: str, cov: str, phase: str = "created", status: str = "",
                 block: dict = None) -> list:
    """Чего не хватает каналу для ЭТОГО выпуска, раз он сам не остановлен этим же."""
    if status not in ("pending", "running", "blocked"):
        return []
    at = _PHASE_ORDER.index(phase) if phase in _PHASE_ORDER else len(_PHASE_ORDER)
    out = []
    if not (rew or "").strip() and at == 0:
        out.append({"kind": CHANNEL, "tag": TAGS[CHANNEL], "level": "warn",
                    "title": "у канала не выбран пресет текста",
                    "what": ("Сценарий пишется на умолчаниях рерайта: без имени ведущего, "
                             "без названия канала и без его стиля. Выпуск идёт, но текст "
                             "будет не тот, что задумывался для канала."),
                    "fix": ("Выберите пресет текста в настройках канала (или в пресете "
                            "производства). Уже заказанный текст это не изменит — только "
                            "следующие выпуски.")})
    cover_block = (block or {}).get("title") == "у канала не выбран пресет обложек"
    if not (cov or "").strip() and at < _PHASE_ORDER.index("cover_ready") and not cover_block:
        out.append({"kind": CHANNEL, "tag": TAGS[CHANNEL], "level": "warn",
                    "title": "у канала не выбран пресет обложек",
                    "what": "Ролик соберётся, но выпуск остановится на обложке.",
                    "fix": ("Выберите пресет обложки в настройках канала — тогда выпуск "
                            "пройдёт обложку без остановки.")})
    return out
