#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Публичные страницы для проверки приложения Google — проверка без браузера.

Google смотрит эти страницы глазами ревьюера и сверяет их с тем, что приложение делает.
Поэтому проверяется две вещи: что страница технически годна (откроется у ревьюера как
есть, без внешних ресурсов, и на телефоне) и что в ней стоят те утверждения, на которых
держится заявка: права только на чтение, данные не продаются, как отозвать доступ.

Отдельно — подстановки. Незаменённое `{{ПОЧТА}}` на живой странице это отказ в проверке,
поэтому имена подстановок перечислены здесь списком: любая новая, забытая в README,
валит проверку.

    .venv/bin/python public/check_pages.py
"""
from __future__ import annotations

import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Ровно три подстановки, и они же перечислены в README. Четвёртая, добавленная молча,
# однажды уедет на живую страницу незаменённой.
ПОДСТАНОВКИ = {"{{НАЗВАНИЕ}}", "{{ДОМЕН}}", "{{ПОЧТА}}"}
FAILS = []


def check(label, ok):
    print(("  OK   " if ok else "  FAIL ") + label)
    if not ok:
        FAILS.append(label)


def страница(имя: str) -> str:
    return io.open(os.path.join(HERE, имя), encoding="utf-8").read()


def половины(текст: str) -> tuple:
    """Русская и английская части страницы по отдельности.

    Проверять целую страницу тут нельзя: обязательные ссылки стоят в обеих частях, и
    поиск по всему тексту проходит, даже если в русской половине ссылку потеряли. Такая
    страница годна для ревьюера Google и непригодна для оператора — а он тут главный
    читатель.
    """
    метка = '<div class="en">'
    if метка not in текст:
        return текст, ""
    ру, en = текст.split(метка, 1)
    return ру, en


def main() -> int:
    for имя in ("index.html", "privacy.html", "terms.html"):
        print(f"\n{имя}")
        t = страница(имя)
        check("doctype на месте", t.lstrip().lower().startswith("<!doctype html>"))
        check("кодировка объявлена", 'charset="utf-8"' in t)
        check("viewport задан — откроется на телефоне", 'name="viewport"' in t)
        check("заголовок не пустой", bool(re.search(r"<title>[^<]{3,}</title>", t)))
        check("описание страницы есть", 'name="description"' in t)
        # Самодостаточность: внешний ресурс может не загрузиться у ревьюера, и страница
        # окажется пустой — а это отказ по причине «homepage not accessible».
        check("внешних скриптов нет", "<script" not in t)
        check("внешних стилей нет", "<link" not in t)
        check("картинок нет", "<img" not in t)
        check("тёмная тема учтена", "prefers-color-scheme" in t)
        check("фон задан явно", "background:var(--bg)" in t)
        # Ревьюер Google читает по-английски. Русский текст основной, английский рядом —
        # чтобы заявку не отложили из-за языка.
        check("английская часть есть", 'class="en"' in t)
        check("теги div закрыты", t.count("<div") == t.count("</div>"))
        найдено = set(re.findall(r"\{\{[^}]{1,40}\}\}", t))
        check(f"подстановки только из списка: {sorted(найдено)}",
              найдено and найдено <= ПОДСТАНОВКИ)

    # ─────────── девять обязательных пунктов политики ───────────
    # Для YouTube-скоупов список разделов политики не на усмотрение автора: он задан
    # пунктом III.A.2 (a–i) «YouTube API Services — Developer Policies». Общая справка
    # Google Cloud списка не даёт, и на этом легко успокоиться — а заявку отклонят.
    # Поэтому каждый пункт проверяется отдельно: забытый (h) это отказ.
    print("\nПолитика: девять пунктов III.A.2 YouTube API Services")
    t = страница("privacy.html")
    ind = страница("index.html")
    trm = страница("terms.html")
    check("(a) политика доступна с каждой страницы",
          all('href="/privacy"' in x for x in (ind, trm)))
    check("(b) сказано, что используются API Services YouTube",
          "API Services YouTube" in t and "YouTube API Services" in t)
    ру, en = половины(t)
    check("(c) ссылка на политику Google ровно та, что названа в правилах — в обеих частях",
          all("http://www.google.com/policies/privacy" in x for x in (ру, en)))
    check("(d) перечислено, что приложение получает и хранит",
          "получает, собирает и хранит" in t)
    check("(e) сказано, как используется и передаётся",
          "используем, обрабатываем и передаём" in t)
    check("(f) раскрыта реклама и сторонний контент",
          "не показывает рекламу" in t and "Сторонние лица" in t)
    check("(g) раскрыты cookies и данные на устройстве",
          "Cookies" in t and "cookie сеанса" in t)
    check("(h) ссылка на отзыв доступа ровно та, что названа в правилах — в обеих частях",
          all("https://security.google.com/settings/security/permissions" in x
              for x in (ру, en)))
    check("(i) есть контакт по вопросам конфиденциальности",
          "вопросам конфиденциальности" in t and "mailto:" in t)

    print("\nПолитика: честные утверждения о поведении кода")
    for нужно, зачем in (
            ("только на чтение", "права не дают записи"),
            ("не передаются, не продаются", "данные не продаются"),
            ("аудиовизуальный контент YouTube", "контент YouTube не хранится"),
            ("read-only", "то же по-английски"),
            ("Revoking access", "отзыв доступа по-английски")):
        check(f"{зачем} — «{нужно}»", нужно in t)

    print("\nУсловия использования: требование III.A.1")
    # Правила YouTube требуют двух вещей разом: ссылки на условия YouTube И прямой
    # фразы в СВОИХ условиях о том, что пользователь с ними соглашается.
    ру_t, en_t = половины(trm)
    check("ссылка на условия YouTube есть в обеих частях",
          all("https://www.youtube.com/t/terms" in x for x in (ру_t, en_t)))
    check("и сказано, что пользователь с ними соглашается",
          "соглашаетесь с" in trm and "agree to be bound by" in trm)
    check("условия доступны с домашней страницы", 'href="/terms"' in ind)

    print("\nДомашняя страница описывает приложение, а не только вход")
    t = ind
    for нужно, зачем in (
            ("youtube.readonly", "названо первое право"),
            ("yt-analytics.readonly", "названо второе право"),
            ("Что приложение делает", "описана функциональность"),
            ("/privacy", "ссылка на политику"),
            ("/terms", "ссылка на условия"),
            ("read-only", "по-английски сказано про чтение")):
        check(f"{зачем} — «{нужно}»", нужно in t)
    # «Только страница входа» — прямой повод для отказа. Формы входа здесь нет вовсе.
    check("формы входа на странице нет", "<form" not in t and "password" not in t)

    print()
    if FAILS:
        print(f"ПРОВАЛЕНО: {len(FAILS)}")
        for f in FAILS:
            print("  -", f)
        return 1
    print("все проверки прошли")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
