#!/bin/bash
# БОЕВОЙ режим: настоящие провайдеры, настоящие деньги.
#
# Отличается от dev/run.sh ровно одним: включён планировщик. Без него задачи стоят
# в очереди и их никто не берёт — так и задумано для разбора интерфейса, но для
# настоящего прогона нужен именно он.
#
#   dev/run-live.sh            весь конвейер, кроме заливки
#
# Заливка НЕ пойдёт: ей нужна минская машина с профилями AdsPower. Всё до неё —
# текст, озвучка, кадры, рендер, обложка — идёт здесь.
#
# ─── Что нужно до запуска ───────────────────────────────────────────────────
#
# 1. Файл ключей. По умолчанию ~/video_studio_api_keys.json, путь меняется
#    переменной VS_SERVER_KEYS_PATH. Формат — по семействам:
#
#      {"googler": "...", "openai": "...", "elevenlabs": "...", "veo": "..."}
#
#    Ключи наружу не показываются и в логи не попадают.
#
# 2. ffmpeg. Нужен рендеру: ffmpeg -version должен отвечать.
#
# 3. Короткий текст на первый раз. Ролик на 155 кадров — это 155 платных вызовов.
#    Путь проверяется тем же самым и на пятнадцати.
set -e
# Запас файловых ручек (21.09.2026). В ночь перед показом стенд умер с
# «[Errno 24] Too many open files»: соседи открывали SQLite идиомой
# `with sqlite3.connect(...)`, которая соединение НЕ закрывает, и за полчаса
# накопилось 12 599 ручек. Причина устранена (tests/test_sqlite_fd_leak.py),
# но запас оставляем: macOS по умолчанию даёт процессу мало, а платформа —
# это три сервиса в одном процессе, то есть три бюджета ручек в одном.
ulimit -n 8192 2>/dev/null || true
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

KEYS="${VS_SERVER_KEYS_PATH:-$HOME/video_studio_api_keys.json}"
if [ ! -f "$KEYS" ]; then
  echo "  НЕТ ФАЙЛА КЛЮЧЕЙ: $KEYS"
  echo "  Создайте его или укажите путь: VS_SERVER_KEYS_PATH=/путь dev/run-live.sh"
  echo '  Формат: {"googler": "...", "openai": "...", "elevenlabs": "..."}'
  exit 1
fi
if ! command -v ffmpeg >/dev/null 2>&1; then
  echo "  НЕТ ffmpeg — рендер не пойдёт. Установите: brew install ffmpeg"
  exit 1
fi

export VS_SERVER_KEYS_PATH="$KEYS"
# Тот самый переключатель. В dev/run.sh он выключен: там разбирают интерфейс, а не
# тратят деньги. Здесь планировщик включён, и задачи из очереди действительно берутся.
export VS_SERVER_DISABLE_BACKGROUND=""

echo
echo "  БОЕВОЙ РЕЖИМ: провайдеры настоящие, вызовы платные."
echo "  ключи:    $KEYS"
echo "  ffmpeg:   $(command -v ffmpeg)"
echo "  заливка:  не пойдёт (нужна минская машина) — всё остальное пойдёт"
echo
exec "$ROOT/dev/run.sh"
