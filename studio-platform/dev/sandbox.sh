#!/bin/bash
# Песочница: платформа + подставной провайдер. Ничего не стоит, наружу не ходит.
#
# Зачем: до этого единственный способ проверить платный путь — заплатить. Здесь кадры,
# клипы и обложки заказываются, опрашиваются, скачиваются и ложатся на диск, а денег
# не тратится и интернета не нужно.
#
#   dev/sandbox.sh                     обычное поведение провайдера
#   dev/sandbox.sh --fail-rate 0.3     треть вызовов отвечает отказом
#   dev/sandbox.sh --slow 5            ответ через 5 секунд (проверка таймаутов)
#   dev/sandbox.sh --die-after 10      после десяти вызовов замолкает совсем
#
# Последние три — не забава: именно так провайдер и ведёт себя в плохой день, и именно
# на этом проверяется, что журнал платных вызовов не даёт заплатить дважды.
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PY="$ROOT/.venv/bin/python"
FAKE_PORT="${VS_FAKE_PORT:-9099}"

trap 'kill 0' EXIT
"$PY" "$ROOT/dev/fake_provider.py" --port "$FAKE_PORT" "$@" &
sleep 1

# Все платные адреса — на подставного. Боевые значения остаются значениями по умолчанию
# в коде: песочница ничего не переписывает, она только подставляет окружение.
export VS_GOOGLER_BASE="http://127.0.0.1:$FAKE_PORT"
export VS_VEO_BASE="http://127.0.0.1:$FAKE_PORT"
export FAST_GEN_API_BASE="http://127.0.0.1:$FAKE_PORT"
# Ключи в песочнице не проверяются — но пустой ключ движки считают «не настроено»
# и отказываются работать раньше, чем дойдут до провайдера.
export GOOGLER_API_KEY="${GOOGLER_API_KEY:-sandbox-key}"
export VEO_API_KEY="${VEO_API_KEY:-sandbox-key}"

echo
echo "  ПЕСОЧНИЦА: провайдер подставной, деньги не тратятся"
echo "  провайдер  http://127.0.0.1:$FAKE_PORT"
echo
exec "$ROOT/dev/run.sh"
